/// Idiomas de ONEchat (Etapa 5). La interfaz vive en este
/// diccionario ES/EN; el idioma activo sale del perfil del usuario
/// (profiles.language) y se aplica en vivo, igual que el tema.
/// Español es el idioma de origen del producto.
final appLanguage = ValueNotifier<String>('es');

void applyProfileLanguage(Map<String, dynamic>? profile) {
  appLanguage.value = profile?['language'] == 'en' ? 'en' : 'es';
}

/// Texto de interfaz por clave. `{x}` se reemplaza con params.
String t(String key, [Map<String, String> params = const {}]) {
  var s = (_dict[appLanguage.value] ?? _es)[key] ?? _es[key] ?? key;
  params.forEach((k, v) => s = s.replaceAll('{$k}', v));
  return s;
}

